<script>
(function () {
    var SUBMIT_URL = '<?= base_url("Modal_submissions/submit") ?>';

    function usmlToast(msg, type) {
        var t = document.getElementById('pgs-toast');
        if (!t) return;
        t.textContent = msg;
        t.className = 'show toast-' + type;
        setTimeout(function () { t.className = ''; }, 3500);
    }

    document.addEventListener('click', function (e) {
        var btn = e.target.closest('#USMLapplicantPremiumModal .cta-btn');
        if (!btn) return;
        e.stopImmediatePropagation();
        e.preventDefault();

        var modal = document.getElementById('USMLapplicantPremiumModal');
        var name  = ((modal.querySelector('#nameInput')  || {}).value || '').trim();
        var email = ((modal.querySelector('#emailInput') || {}).value || '').trim();
        var phone = ((modal.querySelector('#phoneInput') || {}).value || '').trim();

        if (!name) {
            usmlToast('Please enter your name.', 'error');
            var inp = modal.querySelector('#nameInput'); if (inp) inp.focus();
            return;
        }
        if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
            usmlToast('Please enter a valid email address.', 'error');
            var inp = modal.querySelector('#emailInput'); if (inp) inp.focus();
            return;
        }

        var checklistItems = [];
        modal.querySelectorAll('.toggle-list .toggle-row').forEach(function (row) {
            var cb = row.querySelector('input[type="checkbox"]');
            if (cb && cb.checked) {
                var spans = row.querySelectorAll('span');
                var label = spans[spans.length - 1] ? spans[spans.length - 1].textContent.trim() : '';
                if (label) checklistItems.push(label);
            }
        });

        var planningBtn = modal.querySelector('button.modal-btn-pgs');
        var planning = planningBtn ? planningBtn.textContent.replace(/\s+/g, ' ').trim() : '';

        var params = 'modal_type=applicant'
            + '&name='              + encodeURIComponent(name)
            + '&email='             + encodeURIComponent(email)
            + '&phone='             + encodeURIComponent(phone)
            + '&planning_to_study=' + encodeURIComponent(planning)
            + '&source_page='       + encodeURIComponent(window.location.pathname);
        checklistItems.forEach(function (item) {
            params += '&checklist_items[]=' + encodeURIComponent(item);
        });

        var xhr = new XMLHttpRequest();
        xhr.open('POST', SUBMIT_URL, true);
        xhr.setRequestHeader('Content-Type', 'application/x-www-form-urlencoded');
        xhr.onload = function () {
            try {
                var res = JSON.parse(xhr.responseText);
                if (res.success) {
                    usmlToast('Submitted successfully! 🎉', 'success');
                    if (typeof window.USMLapplicatCloseModal === 'function') window.USMLapplicatCloseModal();
                    if (typeof window.USMLapplicantPremiumOpen2 === 'function') window.USMLapplicantPremiumOpen2();
                } else {
                    usmlToast(res.message || 'Submission failed. Please try again.', 'error');
                }
            } catch (err) {
                usmlToast('Something went wrong. Please try again.', 'error');
            }
        };
        xhr.onerror = function () { usmlToast('Network error. Please check your connection.', 'error'); };
        xhr.send(params);
    }, true);
})();
</script>

